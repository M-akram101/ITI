def Sum(*args):
    summation = 0
    for arg in args:
        summation += arg
    print(summation)


def Sub(n1, n2):
    subtraction = n1 - n2
    print(subtraction)


def Div(n1, n2):
    division = n1 / n2
    print(division)


def Mul(n1, n2):
    Multiplication = n1 * n2
    print(Multiplication)
